#!/usr/bin/env node
/* Shared music library generator.
   Reads ../manifest.json, pulls each track's createPlayer (plus the constants and helpers declared
   before it in the game's `Music` module) out of <game>/<game>.html, and writes:
     ../tracks/<id>.js   lazy-loaded factory: ArschulMusic.factories[id]() -> createPlayer
     ../index.js         track metadata for picker.js (titles, moods, mode/cue maps, loudness)
   The games stay the source of truth: edit a game's music in its own file, then re-run this.
   Usage (from games/shared/music/tools):  npm install && node build.js [id ...]          */
const fs = require('fs'), path = require('path');
const acorn = require('acorn'), walk = require('acorn-walk');

const MUSIC = path.resolve(__dirname, '..');
const GAMES = path.resolve(MUSIC, '..', '..');
const manifest = JSON.parse(fs.readFileSync(path.join(MUSIC, 'manifest.json'), 'utf8'));
const only = process.argv.slice(2);

function inlineScripts(html) {
  const re = /<script\b([^>]*)>([\s\S]*?)<\/script>/gi, out = []; let m;
  while ((m = re.exec(html))) if (!/\bsrc\s*=/.test(m[1])) out.push(m[2]);
  return out;
}
function declNames(st) {
  if (st.type === 'FunctionDeclaration') return [st.id.name];
  if (st.type === 'VariableDeclaration') return st.declarations.map(d => d.id.name).filter(Boolean);
  return [];
}
function extract(id) {
  const file = path.join(GAMES, id, id + '.html');
  for (const code of inlineScripts(fs.readFileSync(file, 'utf8'))) {
    if (!/\bMusic\s*=/.test(code)) continue;
    let ast;
    try { ast = acorn.parse(code, { ecmaVersion: 'latest', sourceType: 'script' }); } catch (e) { continue; }
    let decl = null;
    walk.simple(ast, { VariableDeclarator(n) { if (n.id.name === 'Music' && n.init && n.init.type === 'CallExpression') decl = n; } });
    if (!decl) continue;
    const fn = decl.init.callee;
    const body = fn.body.body;
    const cp = body.findIndex(st => declNames(st).includes('createPlayer'));
    if (cp < 0) throw new Error(id + ': no createPlayer in Music');
    // Everything up to and including createPlayer: constants, scales, helpers. Not the live controller.
    let src = body.slice(0, cp + 1).map(st => code.slice(st.start, st.end)).join('\n');
    const strict = body[0] && body[0].type === 'ExpressionStatement' && body[0].directive === 'use strict';
    return { src, strict, file };
  }
  throw new Error(id + ': no Music module found');
}

fs.mkdirSync(path.join(MUSIC, 'tracks'), { recursive: true });
for (const t of manifest.tracks) {
  if (only.length && !only.includes(t.id)) continue;
  const { src, strict } = extract(t.id);
  const out = `/* Generated by shared/music/tools/build.js from ${t.id}/${t.id}.html. Do not edit: change the game, then rebuild. */
(function () {
  var M = window.ArschulMusic = window.ArschulMusic || {};
  (M.factories = M.factories || {})[${JSON.stringify(t.id)}] = function () {
${strict ? "    'use strict';\n" : ''}${src.replace(/^/gm, '    ')}
    return createPlayer;
  };
})();
`;
  // syntax check
  new Function(out.replace(/^\(function/, 'return (function'));
  fs.writeFileSync(path.join(MUSIC, 'tracks', t.id + '.js'), out);
  console.log('track', t.id, (out.length / 1024).toFixed(1) + ' KB');
}
const index = {
  moods: manifest.moods,
  tracks: manifest.tracks.map(t => ({ id: t.id, title: t.title, from: t.from, mood: t.mood, modes: t.modes, play: t.play, cues: t.cues, cueOut: t.cueOut, startVol: t.startVol !== false, cueAt: t.cueAt !== false, rms: t.rms || null }))
};
fs.writeFileSync(path.join(MUSIC, 'index.js'), `/* Generated by shared/music/tools/build.js from manifest.json. Do not edit. */
(window.ArschulMusic = window.ArschulMusic || {}).index = ${JSON.stringify(index, null, 1)};
`);
console.log('index', index.tracks.length, 'tracks');
